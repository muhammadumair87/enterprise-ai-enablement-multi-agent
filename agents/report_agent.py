import json
from typing import Optional
from openai import OpenAI


client = OpenAI()


def generate_governance_report(
    user_request: str,
    coordinator_result: dict,
    specialist_results: list,
    capacity_analysis: Optional[dict] = None
) -> dict:
    """
    Governance Decision / Report Agent

    Reconciles:
    - the original request
    - coordinator routing
    - specialist agent findings
    - deterministic capacity analysis

    Deterministic calculations from the capacity optimizer
    must be treated as the numerical source of truth.

    This agent provides recommendations only.
    It does not execute administrative changes.
    """

    context = {
        "user_request": user_request,
        "coordinator_result": coordinator_result,
        "capacity_analysis": capacity_analysis,
        "specialist_results": specialist_results
    }

    prompt = f"""
You are the final Governance Decision Agent for an
Enterprise AI Enablement and R&D Operations function.

You receive:

1. The original business request.
2. The Coordinator's routing decision.
3. Specialist agent findings.
4. Optional deterministic capacity calculations
   generated by a Python governance engine.

Your job is to reconcile all available evidence into
one management-ready governance decision.

IMPORTANT SOURCE-OF-TRUTH RULE:

If capacity_analysis is present, all numerical values
inside it were calculated deterministically by Python.

Treat those numbers as the source of truth.

Do NOT:
- recalculate forecast values
- invent alternative transfer amounts
- change donor or receiver departments
- claim that a recommended reallocation already happened
- claim that a vendor supports reallocation unless confirmed
- invent savings that were not calculated

You MAY explain the operational implications of those
calculations.

Governance principles:

1. Do not invent facts.

2. Security and privacy risks must not be ignored
   because a tool offers productivity benefits.

3. High utilisation alone does not justify additional spend.

4. Low utilisation alone does not justify removing
   licences or capacity.

5. Prefer optimisation of existing capacity before
   purchasing additional capacity when justified.

6. Capacity reallocations should remain temporary,
   reversible and subject to human approval unless
   an approved automated policy explicitly exists.

7. Consider:
   - business criticality
   - upcoming workload
   - seasonality
   - reporting accuracy
   - automation activity
   - safety buffers
   - vendor/platform capability
   - auditability
   - rollback requirements

8. Clearly identify conflicts and trade-offs between
   specialist recommendations.

9. High-impact changes require human approval.

10. When uncertainty remains, recommend validation,
    monitoring or a controlled pilot rather than
    pretending certainty exists.

Allowed final_decision values:

- APPROVE
- APPROVE_WITH_CONTROLS
- CONDITIONAL_PILOT
- HOLD_FOR_REVIEW
- DO_NOT_APPROVE

Return ONLY valid JSON using exactly this structure:

{{
  "agent": "report_agent",
  "final_decision": "APPROVE|APPROVE_WITH_CONTROLS|CONDITIONAL_PILOT|HOLD_FOR_REVIEW|DO_NOT_APPROVE",
  "overall_risk": "low|medium|high",
  "executive_summary": "short management-ready summary",
  "key_findings": [
    "finding"
  ],
  "capacity_reallocation_summary": [
    "capacity finding or proposed transfer"
  ],
  "conflicts_or_tradeoffs": [
    "tradeoff"
  ],
  "decision_conditions": [
    "condition"
  ],
  "recommended_actions": [
    "action"
  ],
  "requires_human_approval": true
}}

INPUT:

{json.dumps(context, indent=2)}
"""

    response = client.responses.create(
        model="gpt-5.6-luna",
        input=prompt
    )

    raw_output = response.output_text.strip()

    try:
        return json.loads(raw_output)

    except json.JSONDecodeError:

        return {
            "agent": "report_agent",
            "final_decision": "HOLD_FOR_REVIEW",
            "overall_risk": "unknown",
            "executive_summary":
                "Governance Decision Agent returned invalid structured output.",
            "key_findings": [],
            "capacity_reallocation_summary": [],
            "conflicts_or_tradeoffs": [],
            "decision_conditions": [],
            "recommended_actions": [],
            "requires_human_approval": True,
            "raw_output": raw_output
        }